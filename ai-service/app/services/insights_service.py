"""Data-driven insights computed from aggregates the backend sends.

Every insight is a plain computation over the supplied numbers, carries its
sample size, and is skipped (with a reason) when the sample is smaller than
``min_sample_size``. Nothing is generated by a language model.
"""

from __future__ import annotations

import math

import numpy as np
import numpy.typing as npt

from app.schemas.insights import (
    CollectionPoint,
    Confidence,
    Insight,
    InsightsRequest,
    InsightsResponse,
    InsightType,
    MonthPoint,
    SkippedInsight,
    UnmetCategoryPoint,
    WeekdayPoint,
)
from app.utils.text import fmt_distance, fmt_number

SIMILAR_PCT = 10.0  # differences within +/-10% are reported as similar
Z_95 = 1.96


def _confidence(n: int, minimum: int) -> Confidence:
    if n >= 5 * minimum:
        return "HIGH"
    if n >= 2 * minimum:
        return "MEDIUM"
    return "LOW"


def _skip(kind: InsightType, reason: str) -> SkippedInsight:
    return SkippedInsight(type=kind, reason=reason)


def _insufficient(kind: InsightType, n: int, minimum: int) -> SkippedInsight:
    return _skip(kind, f"insufficient sample (n={n} < {minimum})")


# --------------------------------------------------------------------------- weekend vs weekday


def weekend_vs_weekday(points: list[WeekdayPoint], minimum: int) -> Insight | SkippedInsight:
    kind: InsightType = "WEEKEND_VS_WEEKDAY"
    n = sum(p.count for p in points)
    if n < minimum:
        return _insufficient(kind, n, minimum)
    quantity = dict.fromkeys(range(1, 8), 0.0)
    count = dict.fromkeys(range(1, 8), 0)
    for p in points:
        quantity[p.weekday] += p.quantity
        count[p.weekday] += p.count
    weekday_avg = sum(quantity[d] for d in range(1, 6)) / 5.0
    weekend_avg = (quantity[6] + quantity[7]) / 2.0
    weekday_n = sum(count[d] for d in range(1, 6))
    weekend_n = count[6] + count[7]
    if weekday_avg == 0 and weekend_avg == 0:
        return _skip(kind, "no donated quantity recorded")

    diff_pct: float | None = None
    if weekday_avg > 0:
        pct = (weekend_avg - weekday_avg) / weekday_avg * 100.0
        diff_pct = pct
        if abs(pct) < SIMILAR_PCT:
            title = "Weekend and weekday donation volumes are similar"
        else:
            direction = "higher" if pct > 0 else "lower"
            title = f"Weekend donations are {fmt_number(abs(pct))}% {direction} than weekdays"
    else:
        title = "Donations happen only at weekends"
    confidence = _confidence(n, minimum)
    if min(weekday_n, weekend_n) < 5:
        confidence = "LOW"
    return Insight(
        type=kind,
        title=title,
        body=(
            f"On average {fmt_number(weekend_avg)} units were donated per weekend day versus "
            f"{fmt_number(weekday_avg)} per weekday, across {n} donations "
            f"({weekend_n} at weekends, {weekday_n} on weekdays)."
        ),
        sample_size=n,
        confidence=confidence,
        supporting_data={
            "weekday_avg_quantity_per_day": round(weekday_avg, 2),
            "weekend_avg_quantity_per_day": round(weekend_avg, 2),
            "weekday_donations": weekday_n,
            "weekend_donations": weekend_n,
            "difference_pct": None if diff_pct is None else round(diff_pct, 1),
            "quantity_by_iso_weekday": {str(d): round(quantity[d], 2) for d in range(1, 8)},
        },
        limitations=[
            "Per-day averages assume each weekday occurs equally often in the period "
            "(weekday total / 5, weekend total / 2).",
            "Describes a difference; it does not explain why it exists.",
        ],
    )


# --------------------------------------------------------------------------- unmet demand


def unmet_demand(points: list[UnmetCategoryPoint], minimum: int) -> Insight | SkippedInsight:
    kind: InsightType = "UNMET_DEMAND"
    n = sum(p.open_requests for p in points)
    if n < minimum:
        return _insufficient(kind, n, minimum)
    ranked = sorted(
        points,
        key=lambda p: (
            -p.open_requests,
            -p.quantity_remaining,
            p.category_code,
            p.dietary_requirement.value,
        ),
    )
    top = ranked[0]
    share = top.open_requests / n * 100.0
    label = f"{top.category_code} ({top.dietary_requirement.value})"
    return Insight(
        type=kind,
        title=f"Most unmet requests are for {label}",
        body=(
            f"{top.open_requests} of {n} open requests ({fmt_number(share)}%) are for {label}, "
            f"with {fmt_number(top.quantity_remaining)} units still needed."
        ),
        sample_size=n,
        confidence=_confidence(n, minimum),
        supporting_data={
            "top": {
                "category_code": top.category_code,
                "dietary_requirement": top.dietary_requirement.value,
                "open_requests": top.open_requests,
                "quantity_remaining": top.quantity_remaining,
                "share_of_open_requests_pct": round(share, 1),
            },
            "categories": [
                {
                    "category_code": p.category_code,
                    "dietary_requirement": p.dietary_requirement.value,
                    "open_requests": p.open_requests,
                    "quantity_remaining": p.quantity_remaining,
                }
                for p in ranked[:10]
            ],
        },
        limitations=[
            "A snapshot of currently open requests; it does not show how long they have been open.",
            "Quantities are in each category's own unit and are not comparable across categories.",
        ],
    )


# --------------------------------------------------------------------------- distance vs delay


def _average_ranks(values: npt.NDArray[np.float64]) -> npt.NDArray[np.float64]:
    order = np.argsort(values, kind="mergesort")
    ranks = np.empty(values.size, dtype=np.float64)
    ranks[order] = np.arange(1, values.size + 1, dtype=np.float64)
    _, inverse, counts = np.unique(values, return_inverse=True, return_counts=True)
    sums = np.bincount(inverse, weights=ranks)
    return (sums / counts)[inverse]


def spearman(x: npt.NDArray[np.float64], y: npt.NDArray[np.float64]) -> float:
    """Spearman rank correlation with average ranks for ties."""
    return float(np.corrcoef(_average_ranks(x), _average_ranks(y))[0, 1])


def distance_delay(points: list[CollectionPoint], minimum: int) -> Insight | SkippedInsight:
    kind: InsightType = "DISTANCE_DELAY"
    n = len(points)
    if n < max(minimum, 3):
        return _insufficient(kind, n, max(minimum, 3))
    distance = np.array([p.distance_m for p in points], dtype=np.float64)
    delay = np.array([p.delay_minutes for p in points], dtype=np.float64)
    if np.ptp(distance) == 0 or np.ptp(delay) == 0:
        return _skip(kind, "no variation in distance or delay")
    rho = spearman(distance, delay)
    if abs(rho) >= 1.0:
        z = math.inf
    else:
        z = math.atanh(rho) * math.sqrt((n - 3) / 1.06) if n > 3 else 0.0
    significant = abs(z) >= Z_95
    strength = (
        "No meaningful"
        if abs(rho) < 0.1
        else "Weak"
        if abs(rho) < 0.3
        else "Moderate"
        if abs(rho) < 0.5
        else "Strong"
    )
    if abs(rho) < 0.1:
        title = "No meaningful association between collection distance and delay"
    else:
        direction = "longer" if rho > 0 else "shorter"
        title = f"{strength} association: longer collection distances go with {direction} delays"
    median = float(np.median(distance))
    far = delay[distance > median]
    near = delay[distance <= median]
    confidence: Confidence = ("HIGH" if n >= 5 * minimum else "MEDIUM") if significant else "LOW"
    return Insight(
        type=kind,
        title=title,
        body=(
            f"Across {n} collections the Spearman rank correlation between distance and delay is "
            f"{rho:.2f}. Collections farther than the median distance ({fmt_distance(median)}) "
            f"averaged {fmt_number(float(far.mean()) if far.size else 0.0)} min of delay versus "
            f"{fmt_number(float(near.mean()))} min for nearer ones. This is a correlation, not "
            "causation: traffic, time of day or the people involved may explain it."
        ),
        sample_size=n,
        confidence=confidence,
        supporting_data={
            "spearman_rho": round(rho, 4),
            "approx_z": None if math.isinf(z) else round(z, 3),
            "significant_at_95pct_approx": significant,
            "median_distance_m": round(median, 1),
            "mean_delay_far_min": round(float(far.mean()), 2) if far.size else None,
            "mean_delay_near_min": round(float(near.mean()), 2),
        },
        limitations=[
            "Correlation, not causation.",
            "Significance uses an approximate Fisher z-test for Spearman's rho.",
        ],
    )


# --------------------------------------------------------------------------- monthly trend


def _month_index(month: str) -> int:
    year, mon = month.split("-")
    return int(year) * 12 + int(mon) - 1


def trend(points: list[MonthPoint], minimum: int) -> Insight | SkippedInsight:
    kind: InsightType = "TREND"
    months = sorted(points, key=lambda p: p.month)
    if len(months) < 2:
        return _skip(kind, f"need at least 2 months of data (got {len(months)})")
    last, prev = months[-1], months[-2]
    limitations = [
        "If the latest month is still in progress, its total is incomplete.",
        "Month-to-month changes can reflect seasonality (festivals, monsoon) rather than a "
        "lasting trend.",
    ]
    if last.count is not None and prev.count is not None:
        n = last.count + prev.count
    else:
        n = round(last.quantity + prev.quantity)
        limitations.append(
            "Sample size is measured in units because per-month collection counts were not "
            "provided."
        )
    if n < minimum:
        return _insufficient(kind, n, minimum)
    if _month_index(last.month) - _month_index(prev.month) != 1:
        limitations.append(f"{prev.month} and {last.month} are not consecutive months.")

    change: float | None = None
    if prev.quantity > 0:
        pct = (last.quantity - prev.quantity) / prev.quantity * 100.0
        change = pct
        if abs(pct) < SIMILAR_PCT:
            title = f"Completed quantity in {last.month} was similar to {prev.month}"
        else:
            direction = "up" if pct > 0 else "down"
            title = f"Completed quantity {direction} {fmt_number(abs(pct))}% in {last.month}"
        change_text = f" ({pct:+.0f}%)"
    else:
        title = (
            f"Completions resumed in {last.month}"
            if last.quantity > 0
            else (f"No completions in {prev.month} or {last.month}")
        )
        change_text = ""
    body = (
        f"{fmt_number(last.quantity)} units were completed in {last.month} versus "
        f"{fmt_number(prev.quantity)} in {prev.month}{change_text}."
    )
    supporting: dict[str, object] = {
        "last_month": last.month,
        "last_quantity": last.quantity,
        "previous_month": prev.month,
        "previous_quantity": prev.quantity,
        "change_pct": None if change is None else round(change, 1),
    }
    if len(months) >= 4:
        earlier = months[-4:-1]
        avg3 = sum(p.quantity for p in earlier) / 3.0
        body += f" The average of the three months before {last.month} was {fmt_number(avg3)}."
        supporting["previous_3_month_avg"] = round(avg3, 2)
    confidence: Confidence = "LOW" if len(months) < 3 else "MEDIUM"
    if len(months) >= 6 and n >= 5 * minimum:
        confidence = "HIGH"
    return Insight(
        type=kind,
        title=title,
        body=body,
        sample_size=n,
        confidence=confidence,
        supporting_data=supporting,
        limitations=limitations,
    )


# --------------------------------------------------------------------------- entry point


def compute_insights(request: InsightsRequest) -> InsightsResponse:
    minimum = request.min_sample_size
    series = request.series
    no_data = "no data provided"
    outcomes: list[Insight | SkippedInsight] = [
        weekend_vs_weekday(series.donations_by_weekday, minimum)
        if series.donations_by_weekday
        else _skip("WEEKEND_VS_WEEKDAY", no_data),
        unmet_demand(series.unmet_requests_by_category, minimum)
        if series.unmet_requests_by_category
        else _skip("UNMET_DEMAND", no_data),
        distance_delay(series.collections, minimum)
        if series.collections
        else _skip("DISTANCE_DELAY", no_data),
        trend(series.monthly_completed, minimum)
        if series.monthly_completed
        else _skip("TREND", no_data),
    ]
    insights: list[Insight] = []
    skipped: list[SkippedInsight] = []
    for outcome in outcomes:
        if isinstance(outcome, SkippedInsight):
            skipped.append(outcome)
            continue
        if request.data_label != "REAL":
            outcome.limitations.append(
                f"Based on synthetic/demo data (data_label={request.data_label}); not evidence "
                "about real-world operations."
            )
        insights.append(outcome)
    return InsightsResponse(insights=insights, skipped=skipped)
